"""Build helper for the Agentic AI Crash Course website.

The Python files in examples/ are the single source of truth for code.
This script:
  1. Copies each example into the matching <figure class="code-panel"
     data-example="..."> block of every HTML page (so code is visible even
     without JavaScript and works when opening files directly).
  2. Generates a Google Colab notebook per example in notebooks/.
  3. Warns about missing examples and about em dashes in course text.

Usage (from the website folder):
    python tools/build.py

Only the standard library is used.
"""
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "examples"
NOTEBOOKS = ROOT / "notebooks"

# Public URL of the course once GitHub Pages is enabled for the repository.
SITE_URL = "https://agenticaikfupm.github.io/CrashCourse/"

# Example file prefix -> (page, module title) for the notebook header.
MODULES = {
    "evo": ("evolution.html", "Module 1: Evolution of AI"),
    "comp": ("components.html", "Module 2: Components of AI Agents"),
    "pat": ("patterns.html", "Module 3: Agent Design Patterns"),
    "mcp": ("mcp.html", "Module 4: Model Context Protocol"),
    "dec": ("decision-apis.html", "Module 5: Decision APIs"),
    "wf": ("workflows.html", "Module 6: Agentic AI Workflows"),
    "nc": ("no-code.html", "Module 7: No-Code Agentic Workflows"),
    "gov": ("governance.html", "Module 8: Agentic AI Governance"),
}

PANEL_RE = re.compile(
    r'(<figure class="code-panel"[^>]*?data-example="(?P<file>[^"]+)"[^>]*>\s*<pre><code class="language-python">)'
    r"(?P<code>.*?)(</code></pre>)",
    re.DOTALL,
)

REAL_MODEL_MD = """## Optional: try a real open model

The example above uses a small stand-in function so it runs anywhere. The cell
below loads a small open instruction-tuned model from Hugging Face (no API key).
Use `real_llm(prompt)` in place of the stand-in to see how a real model behaves.
The first run downloads about 1 GB."""

REAL_MODEL_CODE = """!pip -q install transformers accelerate
from transformers import pipeline

chat = pipeline("text-generation", model="Qwen/Qwen2.5-0.5B-Instruct")

def real_llm(prompt: str) -> str:
    messages = [{"role": "user", "content": prompt}]
    out = chat(messages, max_new_tokens=200)
    return out[0]["generated_text"][-1]["content"]

print(real_llm("In two sentences, what is an AI agent?"))"""


def split_docstring(source: str) -> tuple[str, str, str]:
    """Return (title, description, code without the module docstring)."""
    m = re.match(r'\s*"""(.*?)"""\s*\n', source, re.DOTALL)
    if not m:
        return "Example", "", source
    doc = m.group(1).strip().splitlines()
    title = doc[0].strip()
    description = "\n".join(doc[1:]).strip()
    return title, description, source[m.end():]


def to_cells(code: str) -> list[str]:
    """Split on '# %%' markers and convert notebook-only lines."""
    # "# %%" starts a new cell; "# %%writefile" stays as the first line of its cell.
    parts = re.split(r"^# %%(?!writefile)[^\n]*\n", code, flags=re.MULTILINE)
    cells = []
    for part in parts:
        lines = part.strip("\n").splitlines()
        if not lines:
            continue
        out = []
        for i, line in enumerate(lines):
            if line.startswith("# !pip"):
                line = line[2:]
            elif i == 0 and line.startswith("# %%writefile"):
                line = line[2:]
            out.append(line)
        text = "\n".join(out)
        # Jupyter and Colab already run an event loop: use top-level await.
        text = re.sub(r"^asyncio\.run\((.+)\)\s*$", r"await \1", text, flags=re.MULTILINE)
        cells.append(text)
    return cells


def nb_cell(kind: str, text: str) -> dict:
    cell = {"cell_type": kind, "metadata": {}, "source": text.splitlines(keepends=True)}
    if kind == "code":
        cell.update({"execution_count": None, "outputs": []})
    return cell


def runs_in_browser(path: Path) -> bool:
    """An example runs in the browser when it imports only the standard library."""
    src = path.read_text(encoding="utf-8")
    return "!pip" not in src


def write_manifest(entries: list[dict]) -> None:
    """assets/data/notebooks.js: used by the home page labs list and the resources page."""
    out = ROOT / "assets" / "data" / "notebooks.js"
    out.write_text(
        "/* Generated by tools/build.py. Do not edit by hand. */\n"
        "window.NOTEBOOKS = " + json.dumps(entries, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )


def build_notebook(path: Path) -> Path:
    source = path.read_text(encoding="utf-8")
    title, description, code = split_docstring(source)
    page, module = MODULES.get(path.stem.split("_")[0], ("index.html", "Agentic AI Crash Course"))
    header = (
        f"# {title}\n\n"
        f"**{module}** of the [Agentic AI Crash Course]({SITE_URL}{page}) by "
        f"[Agentic AI @ KFUPM](https://agenticaikfupm.github.io/).\n\n"
        f"{description}\n\n"
        "Run each cell with **Shift+Enter**. Edit anything and run it again to experiment."
    )
    cells = [nb_cell("markdown", header)] + [nb_cell("code", c) for c in to_cells(code)]
    uses_stand_in = re.search(r"^def (llm|fake_llm)\(", code, re.MULTILINE)
    if uses_stand_in:
        cells += [nb_cell("markdown", REAL_MODEL_MD), nb_cell("code", REAL_MODEL_CODE)]
    nb = {
        "nbformat": 4,
        "nbformat_minor": 4,
        "metadata": {
            "colab": {"provenance": []},
            "kernelspec": {"name": "python3", "display_name": "Python 3"},
            "language_info": {"name": "python"},
        },
        "cells": cells,
    }
    out = NOTEBOOKS / (path.stem + ".ipynb")
    out.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return out


def inject_code() -> list[str]:
    problems = []
    for page in sorted(ROOT.glob("*.html")):
        text = page.read_text(encoding="utf-8")

        def repl(m: re.Match) -> str:
            src = EXAMPLES / m.group("file")
            if not src.exists():
                problems.append(f"{page.name}: missing example {m.group('file')}")
                return m.group(0)
            code = src.read_text(encoding="utf-8").rstrip("\n")
            return m.group(1) + html.escape(code, quote=False) + m.group(4)

        new = PANEL_RE.sub(repl, text)
        if new != text:
            page.write_text(new, encoding="utf-8")
            print(f"updated code panels in {page.name}")
    return problems


def check_style() -> list[str]:
    """Course style rule: no em dashes anywhere in content files."""
    issues = []
    for p in list(ROOT.glob("*.html")) + list(ROOT.glob("*.md")) + list((ROOT / "assets").rglob("*.js")) \
            + list((ROOT / "assets").rglob("*.css")) + list(EXAMPLES.glob("*.py")):
        for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            if "\u2014" in line:
                issues.append(f"{p.relative_to(ROOT)}:{n}: em dash found")
    return issues


def main() -> int:
    NOTEBOOKS.mkdir(exist_ok=True)
    manifest = []
    for ex in sorted(EXAMPLES.glob("*.py")):
        build_notebook(ex)
        title, _, _ = split_docstring(ex.read_text(encoding="utf-8"))
        page, module = MODULES.get(ex.stem.split("_")[0], ("index.html", ""))
        manifest.append({"file": ex.stem, "title": title, "module": module, "page": page,
                         "browser": runs_in_browser(ex)})
    order = list(MODULES)
    manifest.sort(key=lambda m: (order.index(m["file"].split("_")[0]), m["file"]))
    write_manifest(manifest)
    print(f"generated {len(list(EXAMPLES.glob('*.py')))} notebooks in notebooks/")
    problems = inject_code() + check_style()
    for p in problems:
        print("WARNING:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
